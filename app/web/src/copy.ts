/** 学习中(1)/重学中(3) 且已经答过的卡 = 本轮里再次出现的卡 */
export function isRepeatCard(c: { state: number; reps?: number } | null | undefined): boolean {
  return !!c && (c.state === 1 || c.state === 3) && (c.reps ?? 0) > 0;
}
